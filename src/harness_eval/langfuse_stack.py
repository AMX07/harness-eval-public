"""Manage the local self-hosted Langfuse stack (infra/langfuse)."""

from __future__ import annotations

import secrets
import subprocess
import time

import httpx

from .paths import LANGFUSE_DIR, LANGFUSE_ENV, read_env_file

COMPOSE = ["docker", "compose", "-f", str(LANGFUSE_DIR / "docker-compose.yml"), "--env-file", str(LANGFUSE_ENV)]


def init(port: int = 3000) -> bool:
    """Write infra/langfuse/.env with fresh local secrets. Returns False if it already exists."""
    if LANGFUSE_ENV.exists():
        return False
    values = {
        "LANGFUSE_PORT": str(port),
        "NEXTAUTH_URL": f"http://localhost:{port}",
        "NEXTAUTH_SECRET": secrets.token_hex(32),
        "SALT": secrets.token_hex(16),
        "ENCRYPTION_KEY": secrets.token_hex(32),
        "POSTGRES_PASSWORD": secrets.token_hex(16),
        "CLICKHOUSE_PASSWORD": secrets.token_hex(16),
        "REDIS_AUTH": secrets.token_hex(16),
        "MINIO_ROOT_PASSWORD": secrets.token_hex(16),
        "LANGFUSE_INIT_ORG_ID": "harness-eval",
        "LANGFUSE_INIT_ORG_NAME": "Harness Eval",
        "LANGFUSE_INIT_PROJECT_ID": "harness-eval",
        "LANGFUSE_INIT_PROJECT_NAME": "Harness Eval",
        "LANGFUSE_INIT_PROJECT_PUBLIC_KEY": f"pk-lf-{secrets.token_hex(16)}",
        "LANGFUSE_INIT_PROJECT_SECRET_KEY": f"sk-lf-{secrets.token_hex(16)}",
        "LANGFUSE_INIT_USER_EMAIL": "admin@harness-eval.local",
        "LANGFUSE_INIT_USER_NAME": "admin",
        "LANGFUSE_INIT_USER_PASSWORD": secrets.token_urlsafe(18),
    }
    lines = [
        "# Local-only secrets for the self-hosted Langfuse stack. Generated by `hx langfuse init`.",
        "# The UI login is LANGFUSE_INIT_USER_EMAIL / LANGFUSE_INIT_USER_PASSWORD.",
    ]
    lines += [f"{k}={v}" for k, v in values.items()]
    LANGFUSE_ENV.write_text("\n".join(lines) + "\n")
    LANGFUSE_ENV.chmod(0o600)
    return True


def host() -> str:
    port = read_env_file(LANGFUSE_ENV).get("LANGFUSE_PORT", "3000")
    return f"http://localhost:{port}"


def up(wait_seconds: int = 300) -> None:
    init()
    subprocess.run([*COMPOSE, "up", "-d"], check=True)
    deadline = time.time() + wait_seconds
    while time.time() < deadline:
        if healthy():
            return
        time.sleep(3)
    raise TimeoutError(f"Langfuse did not become healthy at {host()} within {wait_seconds}s")


def down(remove_data: bool = False) -> None:
    subprocess.run([*COMPOSE, "down", *(["-v"] if remove_data else [])], check=True)


def healthy() -> bool:
    try:
        r = httpx.get(f"{host()}/api/public/health", timeout=5)
        return r.status_code == 200
    except httpx.HTTPError:
        return False


def status() -> str:
    out = subprocess.run([*COMPOSE, "ps", "--format", "table {{.Service}}\t{{.State}}\t{{.Status}}"], capture_output=True, text=True)
    return out.stdout or out.stderr
